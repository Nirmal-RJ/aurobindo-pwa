function toast(message, activity = null) {
  const node = document.querySelector('#toast');
  clearTimeout(toastTimer);
  activeToast = activity;
  node.textContent = message;
  node.classList.add('visible');
  toastTimer = setTimeout(() => { node.classList.remove('visible'); activeToast = null; }, 4000);
}

